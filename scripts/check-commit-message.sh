#!/usr/bin/env bash
# Enforces the commit format from docs/conventions/04: Conventional Commits.
#
# The scope is OPTIONAL and names an area of the code (`auth`, `ci`, `db`) — not a ticket number.
# A project that requires a ticket ID tightens the regex here; the skeleton assumes no tracker.
#
# Deliberately a script rather than commitlint: this is one regex, and commitlint would add
# node_modules to a path a backend developer may not even have installed.
set -euo pipefail

message_file="${1:?path to the commit message file}"
# The first non-empty, non-comment line — git appends its own '#' instructions below.
subject="$(grep -v '^#' "$message_file" | grep -v '^[[:space:]]*$' | head -n 1 || true)"

# Uppercase in the scope is allowed: a project that adds a tracker (`feat(TEA-1234): ...`)
# has no reason to fight the hook. The type itself must come from the list.
pattern='^(feat|fix|chore|hotfix|refactor|test|docs|revert)(\([A-Za-z0-9._-]+\))?!?: .+'

# Merge and revert messages generated by git have their own, non-negotiable format.
if [[ "$subject" =~ ^(Merge|Revert)\  ]]; then
  exit 0
fi

if [[ ! "$subject" =~ $pattern ]]; then
  cat >&2 <<MSG
Commit message does not match the format from docs/conventions/04.

  Got:      ${subject}
  Pattern:  type: description   or   type(scope): description
  Types:    feat, fix, chore, hotfix, refactor, test, docs, revert
  Examples: feat(auth): add passkey registration
            fix: do not echo the password in the 422 response
MSG
  exit 1
fi
